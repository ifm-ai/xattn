"""Generate the precision-repair backward units.

Families: the grouped (GQA/MQA) main units and their ordered (deterministic)
twins for the square D = V buckets, the grouped rectangular units for D = 256
with a narrower V, and the MHA direct units (square buckets and D = 256 with a
narrower V). Other D != V buckets run the square unit of their larger
dimension. The tile table is the single source of truth for (BlockN, BlockM)
per family, D/V bucket and visibility. Run from any directory; rewrites
csrc/attention/precision/instantiations.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent / 'instantiations'
VISIBILITY = ['CausalFullVisibility', 'CausalSlidingWindowVisibility', 'SlidingChunkVisibility']
DTYPES = [('bf16', 'cutlass::bfloat16_t'), ('fp16', 'cutlass::half_t')]
SQUARE = (64, 128, 256)
RECTANGULAR = ((256, 64), (256, 128))


def tile(family, d, dv):
    """(BlockN, BlockM) for one instance."""
    if family in ('mha_direct', 'main') and d == dv == 64:
        # The dual dS operands need BN=64 to avoid spills.
        return 64, 128
    if family == 'ordered' and d == 64:
        return 64, 128
    return 64, 64


def grouped_unit(family, d, dv, dtype, element, vis):
    """Grouped-head (GQA/MQA) unit; the ordered family is the deterministic
    (ordered dQ) backward."""
    if family == 'main':
        namespace, name = 'xattn::ops::attention::precision', f'Main_{d}_{dtype}_{vis}'
    elif family == 'ordered':
        namespace, name = 'xattn::ops::attention::precision::ordered', f'Main_{d}_{dtype}_{vis}'
    else:
        namespace, name = 'xattn::ops::attention::precision::rectangular', f'Main_{d}_{dv}_{dtype}_{vis}'
    block_n, block_m = tile(family, d, dv)
    deterministic = 'true' if family == 'ordered' else 'false'
    return f'''// Generated by csrc/attention/precision/generate_instantiations.py.
#include "attention/hopper/bwd_template.cuh"
namespace {namespace} {{
void {name}(AttentionBwdParams p,cudaStream_t stream) {{
 using V=attention::semantics::{VISIBILITY[vis]};
 auto launch=[&](auto segment){{
  constexpr bool HasSegment=decltype(segment)::value;
  RunAttentionBwdSm90Kernel<{d},{dv},{block_n},{element},{deterministic},false,HasSegment,{block_m},true,true,V,
   flash::AttentionBwdSm90,0,0,0,false,V::kIsSlidingChunk,V::kIsSlidingChunk,false,true>(p,stream);
 }};
 if(p.q_segment_idx)launch(std::true_type{{}});else launch(std::false_type{{}});
}}
}}
'''


def mha_direct_unit(d, dv, dtype, element, vis):
    """MHA unit whose epilogue writes dK / dV directly."""
    block_n, block_m = tile('mha_direct', d, dv)
    return f'''// Generated by csrc/attention/precision/generate_instantiations.py.
#include "attention/hopper/bwd_template.cuh"
namespace xattn::ops::attention::precision::mha_direct {{
void Main_{d}_{dv}_{dtype}_{vis}(AttentionBwdParams p,cudaStream_t stream) {{
 using V=attention::semantics::{VISIBILITY[vis]};
 auto launch=[&](auto segment){{
  constexpr bool HasSegment=decltype(segment)::value;
  RunAttentionBwdSm90Kernel<{d},{dv},{block_n},{element},false,false,HasSegment,{block_m},false,true,V,
   flash::AttentionBwdSm90,0,0,0,false,V::kIsSlidingChunk,V::kIsSlidingChunk,false,true>(p,stream);
 }};
 if(p.q_segment_idx)launch(std::true_type{{}});else launch(std::false_type{{}});
}}
}}
'''


def main():
    ROOT.mkdir(exist_ok=True)
    for old in ROOT.glob('*.cu'):
        old.unlink()
    for dtype, element in DTYPES:
        for vis in range(3):
            for d in SQUARE:
                (ROOT / f'main_d{d}_{dtype}_v{vis}.cu').write_text(grouped_unit('main', d, d, dtype, element, vis))
                (ROOT / f'ordered_main_d{d}_{dtype}_v{vis}.cu').write_text(
                    grouped_unit('ordered', d, d, dtype, element, vis))
                (ROOT / f'mha_direct_Main_{d}_{d}_{dtype}_{vis}.cu').write_text(mha_direct_unit(d, d, dtype, element, vis))
            for d, dv in RECTANGULAR:
                (ROOT / f'rectangular_Main_{d}_{dv}_{dtype}_{vis}.cu').write_text(
                    grouped_unit('rectangular', d, dv, dtype, element, vis))
                (ROOT / f'mha_direct_Main_{d}_{dv}_{dtype}_{vis}.cu').write_text(
                    mha_direct_unit(d, dv, dtype, element, vis))
    print(len(list(ROOT.glob('*.cu'))), 'units')


if __name__ == '__main__':
    main()
