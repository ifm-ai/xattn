from pathlib import Path
import json
p=Path(__file__).resolve().parent/'instantiations';p.mkdir(exist_ok=True)
manifest=[]
for d in [64,128,256]:
 for dtype,element in [('bf16','cutlass::bfloat16_t'),('fp16','cutlass::half_t')]:
  for vis,name in enumerate(['CausalFullVisibility','CausalSlidingWindowVisibility','SlidingChunkVisibility']):
   fn=f'main_d{d}_{dtype}_v{vis}.cu'
   s=f'''// Generated by csrc/attention/precision/generate_instantiations.py; shared by all six families.
#include "attention/hopper/bwd_template.cuh"
namespace xattn::ops::attention::precision {{
void Main_{d}_{dtype}_{vis}(AttentionBwdParams p,cudaStream_t stream) {{
 using V=attention::semantics::{name};
 auto launch=[&](auto segment,auto level){{
  constexpr bool HasSegment=decltype(segment)::value;
  constexpr int Level=decltype(level)::value;
  RunAttentionBwdSm90Kernel<{d},{d},64,{element},false,false,HasSegment,64,true,Level==4,V,
   flash::AttentionBwdSm90,0,0,0,false,V::kIsSlidingChunk,V::kIsSlidingChunk,false,false,false,false,Level>(p,stream);
 }};
 auto dispatch=[&](auto level){{if(p.q_segment_idx)launch(std::true_type{{}},level);else launch(std::false_type{{}},level);}};
 switch(p.high_precision_level){{
  case 2:dispatch(std::integral_constant<int,2>{{}});break;
  case 3:dispatch(std::integral_constant<int,3>{{}});break;
  case 4:dispatch(std::integral_constant<int,4>{{}});break;
  default:TORCH_CHECK(false,"invalid precision mainloop level");
 }}
}}
}}
'''
   (p/fn).write_text(s)
   for level in [2,3,4]:
    for segments in [False,True]:manifest.append(dict(bucket=d,dtype=dtype,visibility=vis,level=level,segments=segments,deterministic=False,grouped=True,source=fn))
# The manifest is an experiment artifact, not part of the package.
import sys
if len(sys.argv)>1: Path(sys.argv[1]).write_text(json.dumps(manifest,indent=2))
print(len(manifest),'production instances in',len(list(p.glob('*.cu'))),'units')
