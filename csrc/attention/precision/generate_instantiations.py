"""Generate the grouped advanced-precision main units and apply the per-level
tile table to every precision instantiation family.

The table is the single source of truth for (BlockN, BlockM) per family,
D/V bucket, visibility, dtype and level; entries absent from it use the
64x64 tile. Run from any directory; rewrites
csrc/attention/precision/instantiations.
"""
from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parent / 'instantiations'
VISIBILITY = ['CausalFullVisibility', 'CausalSlidingWindowVisibility', 'SlidingChunkVisibility']


def tile(family, d, dv, vis, level, residual=False):
    """(BlockN, BlockM) for one instance; level is 2, 3 or 4. residual marks
    grouped level 2/3 kernels that carry dual P operands for dV."""
    if family in ('mha_direct', 'main') and d == dv == 128:
        # Level 4's dual operands spill with BN=128; BM=128 exceeds shared memory.
        return (128, 64) if level < 4 else (64, 64)
    if family in ('mha_direct', 'main') and d == dv == 64:
        # Level 4's dual dS needs BN=64 to avoid spills.
        return (64, 128) if level == 4 else (128, 128)
    if family in ('mha_direct', 'rectangular') and {d, dv} == {64, 128}:
        # Mixed 64/128 buckets follow D128.
        return (128, 64) if level < 4 else (64, 64)
    if family == 'ordered' and level == 4:
        return (64, 128) if d == 64 else (64, 64)
    if family == 'ordered' and d == 128 and vis == 0 and not residual:
        return 128, 64
    if family == 'ordered' and d == 64:
        return (128, 128) if vis == 0 and not residual else (64, 128)
    return 64, 64


def tile_expr(family, d, dv, vis, index):
    values = [tile(family, d, dv, vis, level)[index] for level in (2, 3, 4)]
    if len(set(values)) == 1:
        return str(values[0])
    return f'(Level==2?{values[0]}:Level==3?{values[1]}:{values[2]})'


def grouped_expr(family, d, dv, vis, index):
    """Tile expression over Level and the dV residual flag of a grouped unit."""
    levels = (2, 3)
    l4 = tile(family, d, dv, vis, 4)[index]
    plain = [tile(family, d, dv, vis, level)[index] for level in levels]
    residual = [tile(family, d, dv, vis, level, True)[index] for level in levels]
    if len({l4, *plain, *residual}) == 1:
        return str(l4)
    def by_level(values):
        return str(values[0]) if values[0] == values[1] else f'(Level==2?{values[0]}:{values[1]})'
    inner = by_level(plain) if plain == residual else f'(decltype(residual)::value?{by_level(residual)}:{by_level(plain)})'
    return f'(Level==4?{l4}:{inner})'


def grouped_unit(family, d, dv, dtype, element, vis, levels):
    """Grouped-head (GQA/MQA) unit. Levels 2/3 use dual P operands for dV
    exactly when keys outnumber queries (previous KV or short Q), as the
    level-0 grouped backward does, so no level loses that residual; level 4
    always uses them. The ordered family is the deterministic (ordered dQ)
    backward."""
    if family == 'main':
        namespace, name = 'xattn::ops::attention::precision', f'Main_{d}_{dtype}_{vis}'
        header = '// Generated by csrc/attention/precision/generate_instantiations.py; shared by all six families.\n'
    elif family == 'ordered':
        namespace, name = 'xattn::ops::attention::precision::ordered', f'Main_{d}_{dtype}_{vis}'
        header = ('// Ordered (deterministic) SM90 backward, shared by all six attention families.\n'
                  '// Generated by csrc/attention/precision/generate_instantiations.py.\n')
    else:
        namespace, name = 'xattn::ops::attention::precision::rectangular', f'Main_{d}_{dv}_{dtype}_{vis}'
        header = '// Generated by csrc/attention/precision/generate_instantiations.py.\n'
    cases = ''.join(f'  case {level}:dispatch(std::integral_constant<int,{level}>{{}});break;\n' for level in levels)
    return f'''{header}#include "attention/hopper/bwd_template.cuh"
namespace {namespace} {{
void {name}(AttentionBwdParams p,cudaStream_t stream) {{
 using V=attention::semantics::{VISIBILITY[vis]};
 auto launch=[&](auto segment,auto level,auto residual){{
  constexpr bool HasSegment=decltype(segment)::value;
  constexpr int Level=decltype(level)::value;
  constexpr bool TwoComponentDV=Level==4 || decltype(residual)::value;
  constexpr int BlockN={grouped_expr(family, d, dv, vis, 0)};
  constexpr int BlockM={grouped_expr(family, d, dv, vis, 1)};
  RunAttentionBwdSm90Kernel<{d},{dv},BlockN,{element},{'true' if family == 'ordered' else 'false'},false,HasSegment,BlockM,true,TwoComponentDV,V,
   flash::AttentionBwdSm90,0,0,0,false,V::kIsSlidingChunk,V::kIsSlidingChunk,false,false,false,false,Level>(p,stream);
 }};
 auto dispatch=[&](auto level){{
  auto with_segment=[&](auto residual){{if(p.q_segment_idx)launch(std::true_type{{}},level,residual);else launch(std::false_type{{}},level,residual);}};
  if constexpr(decltype(level)::value==4) with_segment(std::true_type{{}});
  else if(p.seqlen_k>p.seqlen_q) with_segment(std::true_type{{}});
  else with_segment(std::false_type{{}});
 }};
 switch(p.high_precision_level){{
{cases}  default:TORCH_CHECK(false,"invalid precision mainloop level");
 }}
}}
}}
'''


def retile(path):
    """Rewrite BlockN/BlockM of an mha_direct unit."""
    m = re.fullmatch(r'mha_direct_Main_(\d+)_(\d+)_(bf16|fp16)_(\d)', path.stem)
    if not m:
        return False
    family, d, dv, vis = 'mha_direct', int(m.group(1)), int(m.group(2)), int(m.group(4))
    text = path.read_text()
    head = re.search(r'RunAttentionBwdSm90Kernel<(\d+),(\d+),([^,]+|\([^)]*\)),', text)
    assert head, name
    text = text.replace(head.group(0), f'RunAttentionBwdSm90Kernel<{head.group(1)},{head.group(2)},{tile_expr(family, d, dv, vis, 0)},', 1)
    seg = re.search(r',HasSegment,([^,]+|\([^)]*\)),', text)
    assert seg, name
    text = text.replace(seg.group(0), f',HasSegment,{tile_expr(family, d, dv, vis, 1)},', 1)
    path.write_text(text)
    return True


ROOT.mkdir(exist_ok=True)
manifest = []
for dtype, element in [('bf16', 'cutlass::bfloat16_t'), ('fp16', 'cutlass::half_t')]:
    for vis in range(3):
        for d in [64, 128, 256]:
            fn = f'main_d{d}_{dtype}_v{vis}.cu'
            (ROOT / fn).write_text(grouped_unit('main', d, d, dtype, element, vis, (2, 3, 4)))
            for level in [2, 3, 4]:
                for segments in [False, True]:
                    manifest.append(dict(bucket=d, dtype=dtype, visibility=vis, level=level, segments=segments,
                                         deterministic=False, grouped=True, tile=tile('main', d, d, vis, level),
                                         residual_tile=tile('main', d, d, vis, level, True), source=fn))
            (ROOT / f'ordered_main_d{d}_{dtype}_v{vis}.cu').write_text(grouped_unit('ordered', d, d, dtype, element, vis, (2, 3, 4)))
        # Grouped D != V buckets; level 4 uses the padded square unit unless D is 256.
        for d, dv in [(64, 128), (64, 256), (128, 64), (128, 256), (256, 64), (256, 128)]:
            fn = f'rectangular_Main_{d}_{dv}_{dtype}_{vis}.cu'
            levels = (2, 3, 4) if d == 256 else (2, 3)
            (ROOT / fn).write_text(grouped_unit('rectangular', d, dv, dtype, element, vis, levels))
retiled = sum(retile(p) for p in sorted(ROOT.glob('*.cu')) if p.name.startswith('mha_direct'))
# Optional argument: path for a JSON manifest of the grouped instances.
if len(sys.argv) > 1:
    Path(sys.argv[1]).write_text(json.dumps(manifest, indent=2))
print(len(manifest), 'grouped instances,', retiled, 'retiled units,', len(list(ROOT.glob('*.cu'))), 'units')
